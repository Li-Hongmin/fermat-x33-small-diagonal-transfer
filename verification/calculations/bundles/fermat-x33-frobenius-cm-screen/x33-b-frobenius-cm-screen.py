"""Finite-field Frobenius screen for the order-five Prym factor B.

The curve is

    C: y^33 = prod_i (z-zeta_5^i)^a_i,
    a=(7,28,13,19,10),

and the order-five lift sends the primitive deck characters in the orbits
generated by multiplication by 4.  For q = 1 mod 165, both the branch points
and the lift are defined over F_q.  If L_n is the Kummer sheaf attached to a
primitive character n, then

    tr(Frob_q^r | H^1(C)_n) = - sum_{z in U(F_{q^r})} L_n(z).

The character for r=2 is chosen by a norm-compatible generator: if g_2 is a
generator of F_{q^2}^*, then g_1 = Norm(g_2) is the generator used for F_q.
This avoids changing the embedding of the 33rd roots between r=1 and r=2.

For a rho-orbit representative n, put

    e_2 = (t_1^2-t_2)/2.

The four Frobenius roots have absolute value sqrt(q).  If e_4 is their
product, this gives conjugate(e_2) = q^2*e_2/e_4, hence the determinant
factor is recovered exactly as epsilon = e_4/q^2 = e_2/conjugate(e_2).
Therefore

    P_n(T) = 1 - t_1 T + e_2 T^2
             - q*epsilon*conj(t_1)T^3 + q^2*epsilon T^4.

There is no independent determinant-character choice to enumerate: epsilon is
fixed by the two traces.  The product over the four rho-orbits is consequently
the actual degree-16 Frobenius polynomial of B.

The calculation is a screen only.  In particular, it does not compute
End^0(B) or construct a Chow cycle.
"""

from sage.all import *

M = 33
BRANCH_EXPONENTS = (7, 28, 13, 19, 10)
ORBIT_REPRESENTATIVES = (1, 2, 5, 7)
ORBITS = (
    (1, 4, 16, 25, 31),
    (2, 8, 17, 29, 32),
    (5, 14, 20, 23, 26),
    (7, 10, 13, 19, 28),
)

K = CyclotomicField(M)
w = K.gen()
R = PolynomialRing(K, 'T')
T = R.gen()
conjugation = K.hom([w**(-1)])


def compatible_character_sums(q):
    """Return primitive Kummer sums for r=1 and r=2 over F_q."""
    assert is_prime(q)
    assert (q - 1) % 165 == 0
    F = GF(q**2, 'u')
    g2 = F.multiplicative_generator()
    g1 = g2**(q + 1)
    assert g1.multiplicative_order() == q - 1

    zeta5_1 = g1**((q - 1)//5)
    zeta5_2 = g2**((q**2 - 1)//5)
    # The same branch-point ordering is used at both levels.
    assert zeta5_1 == zeta5_2
    # Fixed choice of prime of the defining field (stated in the paper).
    assert ZZ(zeta5_1) == {331: 64, 661: 247}[q]

    sums = {}
    for r, g, zeta5 in ((1, g1, zeta5_1), (2, g2, zeta5_2)):
        points = [x for x in F if x**q == x] if r == 1 else F
        roots = [zeta5**i for i in range(5)]
        counts = {n: [0]*M for n in range(1, M) if gcd(n, M) == 1}
        for z in points:
            if z in roots:
                continue
            f = F.one()
            for root, exponent in zip(roots, BRANCH_EXPONENTS):
                f *= (z - root)**exponent
            exponent = f.log(g)
            for n in counts:
                counts[n][(n*exponent) % M] += 1
        exact = {
            n: sum(c*K(w**j) for j, c in enumerate(values))
            for n, values in counts.items()
        }
        # rho and Frobenius commute; traces are constant on each orbit.
        for orbit in ORBITS:
            assert all(exact[n] == exact[orbit[0]] for n in orbit)
        sums[r] = exact
    return sums


def conjugate_polynomial(poly):
    return R([conjugation(c) for c in poly.list()])


def frobenius_polynomial(q, exact):
    """Build the actual degree-16 polynomial from the two Kummer traces."""
    factors = []
    epsilons = []
    for n in ORBIT_REPRESENTATIVES:
        t1 = -exact[1][n]
        t2 = -exact[2][n]
        second = (t1**2 - t2)/2
        assert second != 0
        epsilon = second/conjugation(second)
        assert epsilon*conjugation(epsilon) == 1
        epsilons.append(epsilon)
        factors.append(R([
            1,
            -t1,
            second,
            -q*epsilon*conjugation(t1),
            q**2*epsilon,
        ]))
    total = prod(factors)
    # Negative rho-orbits are paired by complex conjugation.
    assert factors[1] == conjugate_polynomial(factors[0])
    assert factors[3] == conjugate_polynomial(factors[2])
    assert all(c in QQ for c in total.list())
    Q = PolynomialRing(QQ, 'U')
    total_q = Q(total)
    X = PolynomialRing(QQ, 'X').gen()
    characteristic = sum(QQ(total_q[i])*X**(16 - i) for i in range(17))
    return characteristic, tuple(epsilons)


def screen(q):
    exact = compatible_character_sums(q)
    print("q", q, "sum selected S_1", sum(exact[1][n] for n in ORBIT_REPRESENTATIVES))
    print("q", q, "sum selected S_2", sum(exact[2][n] for n in ORBIT_REPRESENTATIVES))
    characteristic, epsilons = frobenius_polynomial(q, exact)
    assert characteristic[0] == q**8
    assert characteristic[16] == 1
    assert all(coefficient in ZZ for coefficient in characteristic.list())
    assert characteristic.is_irreducible()
    prime = 13
    discriminant_mod_prime = Integer(characteristic.discriminant()) % prime
    assert discriminant_mod_prime != 0
    factor_degrees = sorted(
        factor.degree() for factor, multiplicity
        in characteristic.change_ring(GF(prime)).factor()
        for _ in range(multiplicity)
    )
    # In an abelian Galois root field all unramified factor degrees are equal.
    assert len(set(factor_degrees)) > 1

    x = characteristic.parent().gen()
    displayed = {331: x**16 + x**15 + 761*x**14 - 13183*x**13 + 147512*x**12 - 9668365*x**11 + 99077160*x**10 - 1981264536*x**9 + 64505725132*x**8 - 655798561416*x**7 + 10854992726760*x**6 - 350620269200215*x**5 + 1770676919700152*x**4 - 52378640371812133*x**3 + 1000812265940691041*x**2 + 435307306210734211*x + 144086718355753023841, 661: x**16 + 6*x**15 + 454*x**14 + 9182*x**13 + 716346*x**12 + 23307588*x**11 + 314636724*x**10 + 16817734524*x**9 + 266633006035*x**8 + 11116522520364*x**7 + 137471392086804*x**6 + 6731342847978228*x**5 + 136750422918799386*x**4 + 1158629510490621782*x**3 + 37867323493919914294*x**2 + 330796927261864273326*x + 36442794820015380778081}[q]
    assert characteristic == displayed, "differs from the polynomial displayed in (1.1a)--(1.1b)"
    print("q", q, "epsilon embeddings", epsilons)
    print("q", q, "Frobenius polynomial", characteristic)
    print("q", q, "irreducible over Q", characteristic.is_irreducible())
    print("q", q, "discriminant mod 13", discriminant_mod_prime)
    print("q", q, "factor degrees mod 13", factor_degrees)
    return characteristic


if __name__ == "__main__":
    for prime in (331, 661):
        screen(prime)
