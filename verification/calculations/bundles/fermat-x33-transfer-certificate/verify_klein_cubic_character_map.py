"""Exact arithmetic for the Klein-cubic to Fermat source correspondence.

This verifies only the monomial map, finite torus kernel, residue-character
table, and finite order-five permutation arithmetic used in the paper, including
the comparison with Billi--Grossi--Marquand's order-five generator. Geometric
residue, Kummer-lift, and boundary-support arguments remain in the manuscript.
"""

from itertools import combinations
from math import gcd


MODULUS = 33
ROWS = (
    (16, -8, 4, -2, 1, 0),
    (1, 16, -8, 4, -2, 0),
    (-2, 1, 16, -8, 4, 0),
    (4, -2, 1, 16, -8, 0),
    (-8, 4, -2, 1, 16, 0),
    (0, 0, 0, 0, 0, 11),
)
R = tuple(row[:5] for row in ROWS[:5])


def determinant_bareiss(matrix):
    """Return an exact determinant using fraction-free elimination."""
    matrix = [list(row) for row in matrix]
    n = len(matrix)
    sign = 1
    previous = 1
    for k in range(n - 1):
        if matrix[k][k] == 0:
            pivot = next((i for i in range(k + 1, n) if matrix[i][k]), None)
            if pivot is None:
                return 0
            matrix[k], matrix[pivot] = matrix[pivot], matrix[k]
            sign = -sign
        pivot_value = matrix[k][k]
        for i in range(k + 1, n):
            for j in range(k + 1, n):
                numerator = matrix[i][j] * pivot_value - matrix[i][k] * matrix[k][j]
                assert numerator % previous == 0
                matrix[i][j] = numerator // previous
        for i in range(k + 1, n):
            matrix[i][k] = 0
        previous = pivot_value
    return sign * matrix[-1][-1]


def rank_mod(matrix, prime):
    """Compute matrix rank over the prime field F_prime."""
    matrix = [[entry % prime for entry in row] for row in matrix]
    rows, columns = len(matrix), len(matrix[0])
    rank = 0
    for column in range(columns):
        pivot = next((i for i in range(rank, rows) if matrix[i][column]), None)
        if pivot is None:
            continue
        matrix[rank], matrix[pivot] = matrix[pivot], matrix[rank]
        inverse = pow(matrix[rank][column], -1, prime)
        matrix[rank] = [(entry * inverse) % prime for entry in matrix[rank]]
        for i in range(rows):
            if i != rank and matrix[i][column]:
                factor = matrix[i][column]
                matrix[i] = [
                    (x - factor * y) % prime
                    for x, y in zip(matrix[i], matrix[rank])
                ]
        rank += 1
        if rank == rows:
            break
    return rank


def main():
    assert all(sum(row) == 11 for row in ROWS)

    # F_cub(phi(x)) = F_33(x), and the projective-torus Jacobian is det(R).
    for i in range(5):
        lhs = tuple(2 * ROWS[i][j] + ROWS[(i + 1) % 5][j] for j in range(6))
        rhs = tuple(33 if j == i else 0 for j in range(6))
        assert lhs == rhs
    assert tuple(3 * value for value in ROWS[5]) == (0, 0, 0, 0, 0, 33)
    assert [sum(R[i][j] for i in range(5)) for j in range(5)] == [11] * 5
    determinant = determinant_bareiss(R)
    assert determinant == 33**4

    # Rank one mod p means four Smith factors are p-divisible. Since
    # v_3(det R) = v_11(det R) = 4, each has valuation one at both primes.
    assert rank_mod(R, 3) == rank_mod(R, 11) == 1

    # The projective kernel's character annihilator is generated by beta_045.
    c = (16, 25, 4, 31, 1)
    row_multipliers = (1, 31, 4, 25, 16)
    for row, multiplier in zip(R, row_multipliers):
        assert tuple(value % MODULUS for value in row) == tuple(
            multiplier * value % MODULUS for value in c
        )
    beta = tuple(
        (11 + ROWS[0][j] + ROWS[4][j] + ROWS[5][j]) % MODULUS
        for j in range(6)
    )
    alpha = (7, 10, 13, 19, 22, 28)
    assert tuple(beta[i] for i in (1, 3, 2, 0, 5, 4)) == alpha
    c_projective = c + ((-sum(c)) % MODULUS,)
    assert c_projective == tuple(13 * value % MODULUS for value in beta)

    units = {u for u in range(1, MODULUS) if gcd(u, MODULUS) == 1}
    seen_units = {}
    for triple in combinations(range(6), 3):
        exponents = tuple(
            10 + sum(ROWS[i][j] for i in triple) for j in range(6)
        )
        assert all(0 <= exponent <= 31 for exponent in exponents)
        assert sum(exponents) == 93
        character = tuple((exponent + 1) % MODULUS for exponent in exponents)
        assert all(character) and sum(character) == 99
        matches = [
            u
            for u in units
            if tuple(u * value % MODULUS for value in beta) == character
        ]
        assert len(matches) == 1
        assert matches[0] not in seen_units
        seen_units[matches[0]] = triple

    assert set(seen_units) == units
    assert len(seen_units) == 20

    # The cubic five-cycle shifts every residue character by 16, while the
    # source rho-action has the same orbit subgroup since 25^3 = 16 mod 33.
    assert pow(25, 3, MODULUS) == 16
    for triple in combinations(range(6), 3):
        character = tuple(
            (11 + sum(ROWS[i][j] for i in triple)) % MODULUS
            for j in range(6)
        )
        shifted = tuple(
            sorted(4 if i == 0 else i - 1 if i < 5 else 5 for i in triple)
        )
        shifted_character = tuple(
            (11 + sum(ROWS[i][j] for i in shifted)) % MODULUS
            for j in range(6)
        )
        assert shifted_character == tuple(
            16 * value % MODULUS for value in character
        )

    # The beta-to-alpha coordinate permutation transports the cubic cycle to
    # rho^2 on the common base. The Kummer lifts can then be aligned by a deck
    # twist: ker(N_16) = (16 - 1)(Z/33), both the multiples of 3.
    tau_on_w = (0, 2, 5, 1, 3, 4)
    sigma_on_w = (0, 4, 3, 5, 2, 1)
    assert tuple(tau_on_w[tau_on_w[tau_on_w[i]]] for i in range(6)) == sigma_on_w

    rho_base = (1, 3, 5, 2, 4, 0)
    rho_base_square = tuple(rho_base[rho_base[i]] for i in range(6))
    beta_to_alpha = (1, 3, 2, 0, 5, 4)
    alpha_to_beta = [0] * 6
    for alpha_index, beta_index in enumerate(beta_to_alpha):
        alpha_to_beta[beta_index] = alpha_index
    sigma_on_alpha = tuple(
        alpha_to_beta[beta_index if beta_index == 5 else (beta_index - 1) % 5]
        for beta_index in beta_to_alpha
    )
    assert rho_base_square == sigma_on_alpha
    norm_16 = sum(pow(16, j, MODULUS) for j in range(5)) % MODULUS
    assert norm_16 == 11
    assert gcd(16 - 1, MODULUS) == 3
    for i in range(5):
        for j in range(5):
            assert ROWS[i][(j - 1) % 5] == ROWS[(i + 1) % 5][j]

    print("det(R) =", determinant)
    print("Smith factors =", (1, 33, 33, 33, 33))
    print("beta_045 =", beta)
    print("residue monomial degree = 93")
    print("20 distinct residue lines =", len(seen_units))
    print("unit orbit =", tuple(sorted(seen_units)))
    print("C5 equivariance arithmetic = PASS")
    print("all_checks = PASS")


if __name__ == "__main__":
    main()
